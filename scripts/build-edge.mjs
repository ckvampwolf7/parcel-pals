/**
 * Bundle the app engine (tracking + wording) into one ESM file for the Supabase Edge Function:
 *   server/engine-entry.ts → supabase/functions/poll/engine.js
 * Run after engine changes, then redeploy the function (see README, "서버").
 */
import { build } from 'rolldown';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';

const root = fileURLToPath(new URL('..', import.meta.url));
await build({
  input: `${root}server/engine-entry.ts`,
  resolve: { alias: { '@': `${root}src` } },
  platform: 'neutral',
  // The server only needs the engine's own wording: stub the screen dictionaries (keeps the upload small).
  plugins: [{
    name: 'stub-ui-dictionaries',
    load(id) { return /[\\/]i18n[\\/]ns[\\/](ui|journey|characters)\.ts$/.test(id) ? 'export default { ko: {}, en: {} };' : null; },
  }],
  output: { file: `${root}supabase/functions/poll/engine.js`, format: 'esm', minify: true },
});
const out = `${root}supabase/functions/poll/engine.js`;
writeFileSync(out, '// @ts-nocheck\n// Generated by scripts/build-edge.mjs from src/engine. Do not edit.\n' + readFileSync(out, 'utf8'));
console.log('built supabase/functions/poll/engine.js');
